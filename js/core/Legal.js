/** Conversione minima da testo marcato a HTML, senza librerie. */
export function testoInHtml(md) {
  const esc = (s) => s.replace(/[&<>]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;' }[c]));
  const righe = esc(md).split('\n');
  const out = [];
  let inLista = false;
  const chiudiLista = () => { if (inLista) { out.push('</ul>'); inLista = false; } };
  for (const r of righe) {
    const t = r.trim();
    if (!t) { chiudiLista(); continue; }
    if (t === '---') { chiudiLista(); out.push('<hr>'); continue; }
    if (t.startsWith('### ')) { chiudiLista(); out.push(`<h4>${grassetto(t.slice(4))}</h4>`); continue; }
    if (t.startsWith('## ')) { chiudiLista(); out.push(`<h3>${t.slice(3)}</h3>`); continue; }
    if (t.startsWith('# ')) { chiudiLista(); out.push(`<h2>${t.slice(2)}</h2>`); continue; }
    if (t.startsWith('- ')) {
      if (!inLista) { out.push('<ul>'); inLista = true; }
      out.push(`<li>${grassetto(t.slice(2))}</li>`);
      continue;
    }
    chiudiLista();
    out.push(`<p>${grassetto(t)}</p>`);
  }
  chiudiLista();
  return out.join('\n');
}

function grassetto(s) {
  return s
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
    .replace(/\*([^*]+)\*/g, '<em>$1</em>')
    .replace(/`([^`]+)`/g, '<code>$1</code>');
}
